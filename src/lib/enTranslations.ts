function localizeManagerNames(value: string): string {
  for (const manager of MANAGERS) value = value.replaceAll(manager.name, manager.nameEn);
  return value;
}

export function localizeShareText(value: string): string {
  if (typeof document === 'undefined' || document.documentElement.lang !== 'en') return value;
  return value.split('\n').map(line => {
    const exact = translateInterface(line);
    if (exact !== line) return exact;
    let result = line;
    for (const [source, target] of Object.entries(TEXT).sort((a, b) => b[0].length - a[0].length)) {
      if (source.length > 3 && result.includes(source)) result = result.replaceAll(source, target);
    }
    return result.replace('#30п0 #ФутбольныйДрафт', '#30to0 #FootballDraft');
  }).join('\n');
}
